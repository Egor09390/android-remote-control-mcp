package com.danielealbano.androidremotecontrolmcp.services.tunnel

import android.content.Context
import com.jcraft.jsch.ChannelExec
import com.jcraft.jsch.ChannelSftp
import com.jcraft.jsch.HostKey
import com.jcraft.jsch.HostKeyRepository
import com.jcraft.jsch.JSch
import com.jcraft.jsch.UserInfo
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream
import java.security.MessageDigest
import java.security.SecureRandom
import java.util.Base64
import java.util.UUID

/** User-initiated SFTP installer for a strictly scoped Docker project on a personally-owned VPS. */
class OwnVpsInstaller(private val context: Context) {
    data class Credentials(
        val host: String,
        val sshPort: Int,
        val username: String,
        val password: String,
        val sshFingerprint: String,
        val domain: String,
    )

    data class Result(val baseUrl: String, val tunnelSecret: String, val report: String)

    suspend fun auditAndDeploy(credentials: Credentials, previousSecret: String): Result =
        withContext(Dispatchers.IO) {
            val host = credentials.host.trim()
            val domain = credentials.domain.trim().lowercase()
            val fingerprint = credentials.sshFingerprint.trim()
            require(host.matches(Regex("^[a-zA-Z0-9.:-]{2,255}$"))) { "Invalid VPS IP/hostname" }
            require(credentials.sshPort in 1..65535) { "Invalid SSH port" }
            require(credentials.username.isNotBlank()) { "SSH user is required" }
            require(credentials.password.isNotEmpty()) { "SSH password is required" }
            require(domain.matches(Regex("^[a-z0-9](?:[a-z0-9.-]{1,251})[a-z0-9]$")) && domain.contains('.')) {
                "A domain pointing at this VPS is required for trusted HTTPS"
            }
            require(fingerprint.matches(Regex("^SHA256:[a-zA-Z0-9+/]{43}$"))) {
                "Enter the trusted SSH server key fingerprint (SHA256:...)"
            }

            val tunnelSecret = previousSecret.takeIf { it.matches(Regex("^[a-f0-9]{64}$")) }
                ?: freshSecret()
            val files = linkedMapOf<String, ByteArray>()
            for (name in listOf("main.go", "adb_bridge.go", "go.mod", "go.sum", "Dockerfile",
                    "docker-compose.yml", "Caddyfile", "android-install.sh")) {
                files[name] = context.assets.open(name).use { it.readBytes() }
            }
            files[".env"] = ("MCP_DOMAIN=" + domain + "\nMCP_TUNNEL_TOKEN=" + tunnelSecret + "\n")
                .toByteArray(Charsets.UTF_8)
            val manifest = buildString {
                for ((name, data) in files) {
                    append(sha256Hex(data))
                    append("  ")
                    append(name)
                    append('\n')
                }
            }.toByteArray(Charsets.UTF_8)
            files[".manifest"] = manifest

            val jsch = JSch()
            jsch.setHostKeyRepository(ExactHostFingerprint(fingerprint))
            val session = jsch.getSession(credentials.username.trim(), host, credentials.sshPort)
            session.setPassword(credentials.password)
            session.setConfig("StrictHostKeyChecking", "yes")
            session.setConfig("PreferredAuthentications", "password")
            session.setServerAliveInterval(20_000)
            try {
                session.connect(20_000)
                val remoteDir = ".android-mcp-staging-" + UUID.randomUUID().toString().replace("-", "")
                val sftp = session.openChannel("sftp") as ChannelSftp
                try {
                    sftp.connect(20_000)
                    val home = sftp.pwd()
                    sftp.mkdir(remoteDir)
                    sftp.chmod(0x1c0, remoteDir)
                    sftp.cd(remoteDir)
                    for ((name, data) in files) {
                        sftp.put(ByteArrayInputStream(data), name)
                        sftp.chmod(0x180, name)
                    }
                    sftp.cd(home)
                    val cmd = session.openChannel("exec") as ChannelExec
                    try {
                        // The stage path is generated by the app; no credentials appear on the command line.
                        val absoluteScript = home.trimEnd('/') + "/" + remoteDir + "/android-install.sh"
                        val quote = "'" + absoluteScript.replace("'", "'\\''") + "'"
                        cmd.setCommand("bash " + quote + " 2>&1")
                        val input = cmd.inputStream
                        cmd.connect(20_000)
                        val output = StringBuilder()
                        input.bufferedReader().use { reader ->
                            while (true) {
                                val line = reader.readLine() ?: break
                                output.append(line).append('\n')
                                if (output.length > 12000) output.delete(0, output.length - 12000)
                            }
                        }
                        val result = output.toString().replace(tunnelSecret, "[redacted]")
                        if (cmd.exitStatus != 0) {
                            error("VPS installation failed: " + result.takeLast(1500))
                        }
                        require("AUDIT_OK" in result) { "VPS did not confirm installation: " + result.takeLast(600) }
                        Result("https://" + domain, tunnelSecret, result.takeLast(1500))
                    } finally {
                        cmd.disconnect()
                        // Do not leave the uploaded .env/tunnel secret in the staging area.
                        runCatching {
                            sftp.cd(home)
                            sftp.cd(remoteDir)
                            files.keys.forEach { sftp.rm(it) }
                            sftp.cd(home)
                            sftp.rmdir(remoteDir)
                        }
                    }
                } finally {
                    sftp.disconnect()
                }
            } finally {
                session.disconnect()
            }
        }

    private fun freshSecret(): String {
        val bytes = ByteArray(32)
        SecureRandom().nextBytes(bytes)
        return bytes.joinToString("") { "%02x".format(it) }
    }

    private fun sha256Hex(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

    /** Reject unknown or changed host keys before sending the SSH password. */
    private class ExactHostFingerprint(private val expected: String) : HostKeyRepository {
        override fun check(host: String?, key: ByteArray?): Int {
            if (key == null) return HostKeyRepository.NOT_INCLUDED
            val digest = MessageDigest.getInstance("SHA-256").digest(key)
            val actual = "SHA256:" + Base64.getEncoder().withoutPadding().encodeToString(digest)
            return if (actual == expected) HostKeyRepository.OK else HostKeyRepository.CHANGED
        }

        override fun add(hostkey: HostKey?, ui: UserInfo?) = Unit
        override fun remove(host: String?, type: String?) = Unit
        override fun remove(host: String?, type: String?, key: ByteArray?) = Unit
        override fun getKnownHostsRepositoryID(): String = "Pinned SHA256 host-key fingerprint"
        override fun getHostKey(): Array<HostKey> = emptyArray()
        override fun getHostKey(host: String?, type: String?): Array<HostKey> = emptyArray()
    }
}
